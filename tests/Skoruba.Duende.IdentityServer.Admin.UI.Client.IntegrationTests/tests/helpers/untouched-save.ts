import { expect, type Page } from "@playwright/test";
import {
  apiDelete,
  apiGet,
  apiPost,
  waitForApiPut,
  type ApiEntity,
} from "./admin-api";
import { clickPageSave } from "./ui-navigation";

export type UntouchedSaveCase = {
  /** API controller, e.g. "Clients" - used for POST, GET {id}, PUT and DELETE. */
  resource: string;
  /** Body of the POST that stores the entity the way another tool would. */
  payload: ApiEntity;
  /** SPA route of the edit form for the stored entity. */
  editUrl: (id: string) => string;
  /** Resolves once the form shows the stored entity, so the save sends it back. */
  waitForForm: (page: Page, stored: ApiEntity) => Promise<void>;
  /** Fields the server changes on every save, e.g. a timestamp. */
  volatileFields?: string[];
};

function isEmpty(value: unknown): boolean {
  return (
    value === null ||
    value === undefined ||
    value === "" ||
    (Array.isArray(value) && value.length === 0)
  );
}

/**
 * Brings a stored entity to the shape that matters for a round trip: NULL, an
 * empty string and an empty list mean the same to IdentityServer, the ids of child rows are
 * regenerated by a save, and the order of collections carries no meaning.
 */
function normalize(value: unknown, dropKeys: ReadonlySet<string>): unknown {
  if (isEmpty(value)) {
    return null;
  }

  if (Array.isArray(value)) {
    return value
      .map((item) => normalize(item, new Set(["id"])))
      .sort((left, right) =>
        JSON.stringify(left).localeCompare(JSON.stringify(right)),
      );
  }

  if (typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value as ApiEntity)
        .filter(([key]) => !dropKeys.has(key))
        .sort(([left], [right]) => left.localeCompare(right))
        .map(([key, item]) => [key, normalize(item, new Set())]),
    );
  }

  return value;
}

/**
 * Opens the edit form of an entity stored through the API, saves it without
 * touching anything and checks the entity is stored exactly as before. This
 * catches what a create/update walk through the form cannot: values the form
 * never produces (NULL, an empty string, a non-default value of a field the
 * form does not show) being replaced by defaults on the way back.
 */
export async function expectSaveWithoutChangesKeepsStoredData(
  page: Page,
  testCase: UntouchedSaveCase,
): Promise<void> {
  const created = await apiPost(page, testCase.resource, testCase.payload);
  const id = String(created.id);
  const entityPath = `${testCase.resource}/${id}`;

  try {
    const before = await apiGet(page, entityPath);

    await page.goto(testCase.editUrl(id));
    await testCase.waitForForm(page, before);

    const saved = waitForApiPut(page, testCase.resource);
    await clickPageSave(page);
    const response = await saved.catch(async (error: Error) => {
      // No request at all means the form refused the stored data.
      const invalidFields = await page
        .locator('[aria-invalid="true"]')
        .evaluateAll((fields) =>
          fields.map((field) => field.getAttribute("name") ?? field.id),
        );
      throw new Error(
        `The form sent no save request (invalid fields: ${invalidFields.join(", ") || "none"}). ${error.message}`,
      );
    });
    expect(response.ok(), "the save request has to succeed").toBe(true);

    const after = await apiGet(page, entityPath);
    const dropKeys = new Set(testCase.volatileFields ?? []);

    expect(
      normalize(after, dropKeys),
      `${testCase.resource} ${id} changed although the form was saved untouched`,
    ).toEqual(normalize(before, dropKeys));
  } finally {
    await apiDelete(page, entityPath);
  }
}
