import { SnippetLanguage } from "@/lib/highlight/highlightCode";

/**
 * Generates the .NET 10 wire-up for a client, derived from the values currently
 * in the client form. The functions here are pure - the tab passes a snapshot
 * in and renders whatever comes out, so the snippets follow unsaved edits.
 *
 * Only the code flow and client credentials scenarios are supported.
 */

/** Scopes that only make sense for a user-facing flow. */
const IDENTITY_ONLY_SCOPES = new Set([
  "openid",
  "profile",
  "email",
  "address",
  "phone",
  "roles",
  "offline_access",
]);

export type SnippetClientConfig = {
  clientId: string;
  scopes: string[];
  requireClientSecret: boolean;
  requirePkce: boolean;
  allowOfflineAccess: boolean;
  requirePushedAuthorization: boolean;
  requireDPoP: boolean;
  redirectUris: string[];
  postLogoutRedirectUris: string[];
};

/**
 * How the application proves its identity at the token endpoint. `jwk` is the
 * private_key_jwt flavour - the client registers a public JWK as its secret and
 * signs an assertion with the matching private key.
 */
export type ClientAuthentication = "shared_secret" | "jwk";

export type SnippetOptions = {
  /** Base address of IdentityServer, e.g. https://localhost:44310 */
  authority: string;
  /** Used for the cookie, the token client and the HttpClient names. */
  appName: string;
  /** Base address of the API the application calls. */
  apiBaseUrl: string;
  /** Read the credential from configuration instead of inlining it in the code. */
  useUserSecrets: boolean;
  clientAuthentication: ClientAuthentication;
};

/** A translatable note rendered below the code of a step. */
export type SnippetMessage = {
  key: string;
  values?: Record<string, string>;
};

export type SnippetBlock = {
  id: string;
  language: SnippetLanguage;
  code: string;
  /** Shown in the block header and used as the download name. */
  fileName?: string;
  isDownloadable?: boolean;
};

export type SnippetStep = {
  id: string;
  titleKey: string;
  descriptionKey?: string;
  blocks: SnippetBlock[];
  notes?: SnippetMessage[];
  warnings?: SnippetMessage[];
};

export type SnippetDocument = {
  steps: SnippetStep[];
};

const PACKAGE_OIDC = "Microsoft.AspNetCore.Authentication.OpenIdConnect";
const PACKAGE_ATM = "Duende.AccessTokenManagement";
const PACKAGE_ATM_OIDC = "Duende.AccessTokenManagement.OpenIdConnect";

/** Configuration section per scenario, so both snippets can live side by side. */
const OIDC_SECTION = "Oidc";
const CLIENT_CREDENTIALS_SECTION = "ClientCredentials";

const secretKey = (section: string) => `${section}:ClientSecret`;
const dPoPKey = (section: string) => `${section}:DPoPJsonWebKey`;
const signingJwkKey = (section: string) => `${section}:SigningJwk`;
const authorityKey = (section: string) => `${section}:Authority`;
const clientIdKey = (section: string) => `${section}:ClientId`;

/** `builder.Configuration["Section:Key"]` as it appears in Program.cs. */
const configuration = (key: string) =>
  `builder.Configuration[${csharpString(key)}]`;

/** Name of the registered HttpClient - it stands for the API being called. */
const API_HTTP_CLIENT_NAME = "api";

/** ASP.NET Core defaults - a snippet that restates them only adds noise. */
const DEFAULT_CALLBACK_PATH = "/signin-oidc";
const DEFAULT_SIGNED_OUT_CALLBACK_PATH = "/signout-callback-oidc";

const SECRET_PLACEHOLDER = "<your client secret>";
const JWK_PLACEHOLDER = "<your private JWK as a single line of JSON>";
const DPOP_KEY_PLACEHOLDER = "<a private JWK generated by this application>";

/**
 * Windows PowerShell 5.1 strips the double quotes of a JSON argument handed to a
 * native command, which leaves a JWK that no longer parses at startup.
 */
const JWK_SHELL_QUOTING_COMMENT =
  '# Windows PowerShell 5.1 drops the double quotes inside the JSON - escape them as \\" there, or use PowerShell 7, cmd or bash';

/**
 * Everything outside printable ASCII is written as \uXXXX. A NUL or one of the
 * other C# line terminators (U+0085, U+2028, U+2029) would break the literal.
 */
export const csharpString = (value: string) =>
  `"${value
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\r/g, "\\r")
    .replace(/\n/g, "\\n")
    .replace(/\t/g, "\\t")
    .replace(
      /[^\x20-\x7e]/g,
      (char) => `\\u${char.charCodeAt(0).toString(16).padStart(4, "0")}`,
    )}"`;

/** Trailing slashes break `new Uri(base)` + relative path composition. */
const trimTrailingSlash = (value: string) => value.replace(/\/+$/, "");

const ensureTrailingSlash = (value: string) =>
  value.endsWith("/") ? value : `${value}/`;

/**
 * ASP.NET Core takes the callback as a path, not a full URI. The form allows
 * values that are not valid absolute URLs (yet), hence the guarded parse.
 */
const derivePath = (uris: string[], fallback: string): string => {
  for (const uri of uris) {
    try {
      const { pathname } = new URL(uri);

      if (pathname && pathname !== "/") {
        return pathname;
      }
    } catch {
      // Not an absolute URI - fall through to the next candidate.
    }
  }

  return fallback;
};

/** An API scope is one the token endpoint can put in an access token. */
const hasApiScope = (scopes: string[]): boolean =>
  scopes.some((scope) => !IDENTITY_ONLY_SCOPES.has(scope));

/**
 * Duende's access token management backs the API HttpClient, the refresh token,
 * the DPoP proof and the client assertion, so any of them pulls it in.
 */
const needsTokenManagement = (
  clientConfig: SnippetClientConfig,
  options: SnippetOptions,
  scopes: string[],
): boolean =>
  hasApiScope(scopes) ||
  clientConfig.allowOfflineAccess ||
  clientConfig.requireDPoP ||
  (clientConfig.requireClientSecret && options.clientAuthentication === "jwk");

/**
 * Reduces a value to `[a-z0-9-]`, which both a cookie name and a named
 * HttpClient accept. Run it over whatever the user types too - a cookie name is
 * a token, so a space in it would break the sign-in without saying anything.
 */
export const toApplicationName = (value: string): string => {
  const name = value
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");

  return name === "" ? "my-app" : name;
};

/**
 * Identity scopes first, API scopes after them, `offline_access` last - the
 * order the scopes are usually written by hand in.
 */
const orderScopes = (scopes: string[], allowOfflineAccess: boolean): string[] => {
  const unique = Array.from(new Set(scopes.filter((scope) => scope !== "")));

  if (allowOfflineAccess && !unique.includes("offline_access")) {
    unique.push("offline_access");
  }

  const weight = (scope: string) => {
    if (scope === "openid") return 0;
    if (scope === "profile") return 1;
    if (scope === "offline_access") return 4;

    return IDENTITY_ONLY_SCOPES.has(scope) ? 2 : 3;
  };

  return unique.sort((left, right) => weight(left) - weight(right));
};

