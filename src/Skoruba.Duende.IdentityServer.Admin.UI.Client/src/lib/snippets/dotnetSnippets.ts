/**
 * Authority and client id live in appsettings.json rather than in the code, so
 * Program.cs and the assertion service read the same values.
 */
const appSettingsStep = (
  section: string,
  clientConfig: SnippetClientConfig,
  options: SnippetOptions,
): SnippetStep => ({
  id: "appsettings",
  titleKey: "Client.Integration.Steps.Settings",
  descriptionKey: "Client.Integration.Steps.SettingsDescription",
  blocks: [
    {
      id: "appsettings",
      language: "json",
      code: JSON.stringify(
        {
          [section]: {
            Authority: trimTrailingSlash(options.authority),
            ClientId: clientConfig.clientId,
          },
        },
        null,
        2,
      ),
      fileName: "appsettings.json",
    },
  ],
});

/**
 * The client credential, which already exists - it was created on the Secrets
 * tab, so this step only moves it into the application's user secrets.
 */
const credentialStep = (
  section: string,
  clientConfig: SnippetClientConfig,
  options: SnippetOptions,
): SnippetStep | null => {
  if (!clientConfig.requireClientSecret || !options.useUserSecrets) {
    return null;
  }

  const isJwk = options.clientAuthentication === "jwk";

  return {
    id: "credential",
    titleKey: isJwk
      ? "Client.Integration.Steps.SigningKey"
      : "Client.Integration.Steps.Secret",
    descriptionKey: isJwk
      ? "Client.Integration.Steps.SigningKeyDescription"
      : "Client.Integration.Steps.SecretDescription",
    blocks: [
      {
        id: "user-secrets",
        language: "bash",
        code: [
          "dotnet user-secrets init",
          ...(isJwk
            ? [
                JWK_SHELL_QUOTING_COMMENT,
                `dotnet user-secrets set "${signingJwkKey(section)}" '${JWK_PLACEHOLDER}'`,
              ]
            : [
                `dotnet user-secrets set "${secretKey(section)}" '${SECRET_PLACEHOLDER}'`,
              ]),
        ].join("\n"),
      },
    ],
    notes: [{ key: "Client.Integration.Notes.CredentialStorage" }],
  };
};

/**
 * The DPoP proof key, which does not exist yet - it belongs to the application
 * alone and is registered nowhere, so it has to be generated first.
 *
 * Where it goes follows the "keep secrets out of the code" switch, like the client
 * credential does. With user secrets the step also initialises them when no
 * credential step ran before it (a public client has none).
 */
const dPoPKeyStep = (
  section: string,
  clientConfig: SnippetClientConfig,
  options: SnippetOptions,
): SnippetStep | null => {
  if (!clientConfig.requireDPoP) {
    return null;
  }

  const blocks: SnippetBlock[] = [
    {
      id: "dpop-generate",
      language: "csharp",
      code: [
        "using System.Security.Cryptography;",
        "using System.Text.Json;",
        "using Microsoft.IdentityModel.Tokens;",
        "",
        "var rsa = new RsaSecurityKey(RSA.Create(2048));",
        "var jwk = JsonWebKeyConverter.ConvertFromRSASecurityKey(rsa);",
        'jwk.Alg = "PS256";',
        "",
        "Console.WriteLine(JsonSerializer.Serialize(jwk));",
      ].join("\n"),
    },
  ];

  const notes: SnippetMessage[] = [
    { key: "Client.Integration.Notes.DPoPProofKey" },
    { key: "Client.Integration.Notes.DPoPApiSide" },
  ];

  if (options.useUserSecrets) {
    const hasCredentialStep =
      credentialStep(section, clientConfig, options) !== null;

    blocks.push({
      id: "dpop-user-secrets",
      language: "bash",
      code: [
        ...(hasCredentialStep ? [] : ["dotnet user-secrets init"]),
        JWK_SHELL_QUOTING_COMMENT,
        `dotnet user-secrets set "${dPoPKey(section)}" '${DPOP_KEY_PLACEHOLDER}'`,
      ].join("\n"),
    });
  } else {
    notes.push({ key: "Client.Integration.Notes.DPoPKeyInline" });
  }

  return {
    id: "dpop-key",
    titleKey: "Client.Integration.Steps.DPoPKey",
    descriptionKey: "Client.Integration.Steps.DPoPKeyDescription",
    blocks,
    notes,
  };
};

const secretExpression = (
  configurationKey: string,
  useUserSecrets: boolean,
): string =>
  useUserSecrets
    ? `builder.Configuration[${csharpString(configurationKey)}]`
    : csharpString(SECRET_PLACEHOLDER);

/**
 * The DPoP proof key is a private key, so unlike the shared secret it is never a
 * reasonable thing to leave in the code - the inline form exists only so the
 * generated program compiles and runs when user secrets are switched off.
 */
const dPoPKeyExpression = (section: string, useUserSecrets: boolean): string =>
  useUserSecrets
    ? `DPoPProofKey.Parse(builder.Configuration[${csharpString(dPoPKey(section))}]!)`
    : `DPoPProofKey.Parse(${csharpString(DPOP_KEY_PLACEHOLDER)})`;

/**
 * private_key_jwt support: Duende's access token management asks this service
 * for a freshly signed assertion whenever it authenticates at the token
 * endpoint, so the client never sends a shared secret.
 */
const buildClientAssertionService = (
  section: string,
  options: SnippetOptions,
): string => {
  const jwkExpression = options.useUserSecrets
    ? `configuration[${csharpString(signingJwkKey(section))}]!`
    : csharpString(JWK_PLACEHOLDER);

  return [
    "using Duende.AccessTokenManagement;",
    "using Duende.IdentityModel;",
    "using Duende.IdentityModel.Client;",
    "using Microsoft.IdentityModel.JsonWebTokens;",
    "using Microsoft.IdentityModel.Tokens;",
    "",
    "public class ClientAssertionService(IConfiguration configuration)",
    "    : IClientAssertionService",
    "{",
    `    private readonly string clientId = configuration[${csharpString(clientIdKey(section))}]!;`,
    `    private readonly string authority = configuration[${csharpString(authorityKey(section))}]!;`,
    `    private readonly SigningCredentials credentials = Load(${jwkExpression});`,
    "",
    "    public Task<ClientAssertion?> GetClientAssertionAsync(",
    "        ClientCredentialsClientName? clientName = null,",
    "        TokenRequestParameters? parameters = null,",
    "        CancellationToken ct = default)",
    "    {",
    "        var jwt = new JsonWebTokenHandler().CreateToken(new SecurityTokenDescriptor",
    "        {",
    "            Issuer = clientId,",
    "            Audience = authority,",
    "            Expires = DateTime.UtcNow.AddMinutes(1),",
    "            SigningCredentials = credentials,",
    "",
    "            Claims = new Dictionary<string, object>",
    "            {",
    "                { JwtClaimTypes.JwtId, Guid.NewGuid().ToString() },",
    "                { JwtClaimTypes.Subject, clientId }",
    "            },",
    "",
    '            AdditionalHeaderClaims = new Dictionary<string, object>',
    "            {",
    '                { "typ", "client-authentication+jwt" }',
    "            }",
    "        });",
    "",
    "        return Task.FromResult<ClientAssertion?>(new ClientAssertion",
    "        {",
    "            Type = OidcConstants.ClientAssertionTypes.JwtBearer,",
    "            Value = jwt",
    "        });",
    "    }",
    "",
    "    private static SigningCredentials Load(string jwk)",
    "    {",
    "        var key = new JsonWebKey(jwk);",
    "",
    "        return new SigningCredentials(key, key.Alg",
    '            ?? throw new InvalidOperationException("The signing JWK has no alg."));',
    "    }",
    "}",
  ].join("\n");
};

