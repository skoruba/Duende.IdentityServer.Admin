/**
 * The client credential, which already exists - it was created on the Secrets
 * tab, so this step only moves it into the application's user secrets.
 */
const credentialStep = (
  section: string,
  clientConfig: SnippetClientConfig,
  options: SnippetOptions,
): SnippetStep | null => {
  if (!clientConfig.requireClientSecret || !options.useUserSecrets) {
    return null;
  }

  const isJwk = options.clientAuthentication === "jwk";

  return {
    id: "credential",
    titleKey: isJwk
      ? "Client.Integration.Steps.SigningKey"
      : "Client.Integration.Steps.Secret",
    descriptionKey: isJwk
      ? "Client.Integration.Steps.SigningKeyDescription"
      : "Client.Integration.Steps.SecretDescription",
    blocks: [
      {
        id: "user-secrets",
        language: "bash",
        code: [
          "dotnet user-secrets init",
          isJwk
            ? `dotnet user-secrets set "${signingJwkKey(section)}" "${JWK_PLACEHOLDER}"`
            : `dotnet user-secrets set "${secretKey(section)}" "${SECRET_PLACEHOLDER}"`,
        ].join("\n"),
      },
    ],
    notes: [
      {
        key: isJwk
          ? "Client.Integration.Notes.PrivateJwkNeverLeavesTheApp"
          : "Client.Integration.Notes.SecretNotStored",
      },
    ],
  };
};

