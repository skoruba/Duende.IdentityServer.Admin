export const buildClientCredentialsSnippet = (
  clientConfig: SnippetClientConfig,
  options: SnippetOptions,
): SnippetDocument => {
  const requestedScopes = Array.from(new Set(clientConfig.scopes));
  const scopes = requestedScopes.filter(
    (scope) => !IDENTITY_ONLY_SCOPES.has(scope),
  );
  const droppedScopes = requestedScopes.filter((scope) =>
    IDENTITY_ONLY_SCOPES.has(scope),
  );

  const useJwkAuth =
    clientConfig.requireClientSecret && options.clientAuthentication === "jwk";

  const steps: SnippetStep[] = [
    packageStep([PACKAGE_ATM]),
    appSettingsStep(CLIENT_CREDENTIALS_SECTION, clientConfig, options),
  ];

  const machineSteps = [
    credentialStep(CLIENT_CREDENTIALS_SECTION, clientConfig, options),
    dPoPKeyStep(CLIENT_CREDENTIALS_SECTION, clientConfig, options),
  ].filter((step) => step !== null);

  steps.push(...machineSteps);

  const notes: SnippetMessage[] = [];
  const warnings: SnippetMessage[] = [];

  if (droppedScopes.length > 0) {
    notes.push({
      key: "Client.Integration.Notes.IdentityScopesSkipped",
      values: { scopes: droppedScopes.join(", ") },
    });
  }

  if (scopes.length === 0) {
    warnings.push({ key: "Client.Integration.Notes.NoApiScope" });
  }

  if (!clientConfig.requireClientSecret) {
    warnings.push({ key: "Client.Integration.Notes.MachineClientWithoutSecret" });
  }

  if (!options.useUserSecrets && clientConfig.requireClientSecret) {
    warnings.push({ key: "Client.Integration.Notes.InlineSecret" });
  }

  steps.push({
    id: "program",
    titleKey: "Client.Integration.Steps.Program",
    descriptionKey: "Client.Integration.Steps.WorkerProgramDescription",
    blocks: [
      {
        id: "program",
        language: "csharp",
        code: buildClientCredentialsProgram(clientConfig, options, scopes),
        fileName: "Program.cs",
        isDownloadable: true,
      },
    ],
    notes,
    warnings,
  });

  if (useJwkAuth) {
    steps.push(assertionStep(CLIENT_CREDENTIALS_SECTION, options));
  }

  steps.push({
    id: "worker",
    titleKey: "Client.Integration.Steps.Worker",
    descriptionKey: "Client.Integration.Steps.WorkerDescription",
    blocks: [
      {
        id: "worker",
        language: "csharp",
        code: buildClientCredentialsWorker(),
        fileName: "ApiWorker.cs",
        isDownloadable: true,
      },
    ],
  });

  return { steps };
};

/** All blocks of a document joined together, for the "copy everything" action. */
export const flattenSnippetDocument = (document: SnippetDocument): string =>
  document.steps
    .flatMap((step) => step.blocks.map((block) => block.code))
    .join("\n\n");
