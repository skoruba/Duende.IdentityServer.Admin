const buildAuthorizationCodeProgram = (
  clientConfig: SnippetClientConfig,
  options: SnippetOptions,
  scopes: string[],
): string => {
  const useJwkAuth =
    clientConfig.requireClientSecret && options.clientAuthentication === "jwk";

  // Only these two need a managed HttpClient for calling APIs.
  const useApiHttpClient =
    clientConfig.allowOfflineAccess || clientConfig.requireDPoP;

  // private_key_jwt runs through the same library, so it pulls it in as well.
  const useTokenManagement = useApiHttpClient || useJwkAuth;

  const duendeUsings: string[] = [];

  if (useJwkAuth) {
    duendeUsings.push("using Duende.AccessTokenManagement;");
  }

  if (clientConfig.requireDPoP) {
    duendeUsings.push("using Duende.AccessTokenManagement.DPoP;");
  }

  if (useTokenManagement) {
    duendeUsings.push("using Duende.AccessTokenManagement.OpenIdConnect;");
  }

  const usings = [
    ...duendeUsings,
    "using Microsoft.AspNetCore.Authentication.Cookies;",
    "using Microsoft.AspNetCore.Authentication.OpenIdConnect;",
    "using Microsoft.IdentityModel.Tokens;",
  ];

  const cookieOptions = [
    "        // __Host- requires Secure, Path=/ and no Domain - the browser drops",
    "        // the cookie otherwise, so the app has to be served over HTTPS",
    `        options.Cookie.Name = ${csharpString(`__Host-${options.appName}`)};`,
    '        options.Cookie.Path = "/";',
    "        options.Cookie.SecurePolicy = CookieSecurePolicy.Always;",
    "",
    "        // Strict holds as long as IdentityServer and this app share a site",
    "        options.Cookie.SameSite = SameSiteMode.Strict;",
  ];

  if (clientConfig.allowOfflineAccess) {
    cookieOptions.push(
      "",
      "        // Revokes the refresh token when the user signs out",
      "        options.Events.OnSigningOut = async e =>",
      "            await e.HttpContext.RevokeRefreshTokenAsync();",
    );
  }

  const oidcOptions = [
    "        // The discovery document is loaded from",
    `        // ${trimTrailingSlash(options.authority)}/.well-known/openid-configuration`,
    `        options.Authority = ${configuration(authorityKey(OIDC_SECTION))};`,
    "",
    `        options.ClientId = ${configuration(clientIdKey(OIDC_SECTION))};`,
  ];

  if (useJwkAuth) {
    oidcOptions.push(
      "",
      "        // No ClientSecret - ClientAssertionService signs a private_key_jwt",
    );
  } else if (clientConfig.requireClientSecret) {
    oidcOptions.push(
      `        options.ClientSecret = ${secretExpression(secretKey(OIDC_SECTION), options.useUserSecrets)};`,
    );
  }

  oidcOptions.push(
    "",
    '        options.ResponseType = "code";',
    `        options.UsePkce = ${clientConfig.requirePkce ? "true" : "false"};`,
  );

  if (clientConfig.requirePushedAuthorization) {
    oidcOptions.push(
      "        options.PushedAuthorizationBehavior = PushedAuthorizationBehavior.Require;",
    );
  }

  oidcOptions.push(
    "",
    "        // These paths have to match the URIs registered for the client",
    `        options.CallbackPath = ${csharpString(derivePath(clientConfig.redirectUris, "/signin-oidc"))};`,
    `        options.SignedOutCallbackPath = ${csharpString(derivePath(clientConfig.postLogoutRedirectUris, "/signout-callback-oidc"))};`,
    "",
    "        options.Scope.Clear();",
    ...scopes.map((scope) => `        options.Scope.Add(${csharpString(scope)});`),
    "",
    "        options.GetClaimsFromUserInfoEndpoint = true;",
    "        options.SaveTokens = true;",
    "        options.MapInboundClaims = false;",
    "",
    "        options.TokenValidationParameters = new TokenValidationParameters",
    "        {",
    '            NameClaimType = "name",',
    '            RoleClaimType = "role"',
    "        };",
  );

  const tokenManagement: string[] = [];

  if (useTokenManagement) {
    tokenManagement.push("");

    if (clientConfig.requireDPoP) {
      tokenManagement.push(
        "// The client requires DPoP, so the access token is bound to this key",
        "builder.Services.AddOpenIdConnectAccessTokenManagement(options =>",
        "{",
        `    options.DPoPJsonWebKey = DPoPProofKey.Parse(builder.Configuration[${csharpString(dPoPKey(OIDC_SECTION))}]!);`,
        "});",
      );
    } else {
      tokenManagement.push(
        clientConfig.allowOfflineAccess
          ? "// Refreshes the access token in the background using the refresh token"
          : "// Hooks the client assertion into the code exchange",
        "builder.Services.AddOpenIdConnectAccessTokenManagement();",
      );
    }

    if (useJwkAuth) {
      tokenManagement.push(
        "",
        "builder.Services.AddTransient<IClientAssertionService, ClientAssertionService>();",
      );
    }

    if (useApiHttpClient) {
      tokenManagement.push(
        "",
        `builder.Services.AddUserAccessTokenHttpClient(${csharpString(options.appName)}, configureClient: client =>`,
        "{",
        `    client.BaseAddress = new Uri(${csharpString(ensureTrailingSlash(options.apiBaseUrl))});`,
        "});",
      );
    }
  }

  return [
    ...usings,
    "",
    "var builder = WebApplication.CreateBuilder(args);",
    "",
    "builder.Services.AddAuthentication(options =>",
    "    {",
    "        options.DefaultScheme = CookieAuthenticationDefaults.AuthenticationScheme;",
    "        options.DefaultChallengeScheme = OpenIdConnectDefaults.AuthenticationScheme;",
    "        options.DefaultSignOutScheme = OpenIdConnectDefaults.AuthenticationScheme;",
    "    })",
    "    .AddCookie(options =>",
    "    {",
    ...cookieOptions,
    "    })",
    "    .AddOpenIdConnect(options =>",
    "    {",
    ...oidcOptions,
    "    });",
    ...tokenManagement,
    "",
    "builder.Services.AddAuthorization();",
    "",
    "var app = builder.Build();",
    "",
    "app.UseAuthentication();",
    "app.UseAuthorization();",
    "",
    "app.Run();",
  ].join("\n");
};

export const buildAuthorizationCodeSnippet = (
  clientConfig: SnippetClientConfig,
  options: SnippetOptions,
): SnippetDocument => {
  const scopes = orderScopes(clientConfig.scopes, clientConfig.allowOfflineAccess);

  const useJwkAuth =
    clientConfig.requireClientSecret && options.clientAuthentication === "jwk";

  const packages = [PACKAGE_OIDC];

  if (clientConfig.allowOfflineAccess || clientConfig.requireDPoP || useJwkAuth) {
    packages.push(PACKAGE_ATM_OIDC);
  }

  const steps: SnippetStep[] = [
    packageStep("webapp", packages),
    appSettingsStep(OIDC_SECTION, clientConfig, options),
  ];

  const oidcSteps = [
    credentialStep(OIDC_SECTION, clientConfig, options),
    dPoPKeyStep(OIDC_SECTION, clientConfig),
  ].filter((step) => step !== null);

  steps.push(...oidcSteps);

  const notes: SnippetMessage[] = [];
  const warnings: SnippetMessage[] = [];

  if (!scopes.includes("openid")) {
    warnings.push({ key: "Client.Integration.Notes.MissingOpenIdScope" });
  }

  if (!clientConfig.requirePkce) {
    warnings.push({ key: "Client.Integration.Notes.PkceDisabled" });
  }

  if (!clientConfig.requireClientSecret) {
    notes.push({ key: "Client.Integration.Notes.PublicClient" });
  }

  if (clientConfig.redirectUris.length === 0) {
    warnings.push({ key: "Client.Integration.Notes.NoRedirectUri" });
  }

  if (clientConfig.requireDPoP) {
    notes.push({ key: "Client.Integration.Notes.DPoPRequired" });
  }

  if (!options.useUserSecrets && clientConfig.requireClientSecret) {
    warnings.push({ key: "Client.Integration.Notes.InlineSecret" });
  }

  steps.push({
    id: "program",
    titleKey: "Client.Integration.Steps.Program",
    descriptionKey: "Client.Integration.Steps.ProgramDescription",
    blocks: [
      {
        id: "program",
        language: "csharp",
        code: buildAuthorizationCodeProgram(clientConfig, options, scopes),
        fileName: "Program.cs",
        isDownloadable: true,
      },
    ],
    notes,
    warnings,
  });

  if (useJwkAuth) {
    steps.push(assertionStep(OIDC_SECTION, options));
  }

  return { steps };
};

const buildClientCredentialsProgram = (
  clientConfig: SnippetClientConfig,
  options: SnippetOptions,
  scopes: string[],
): string => {
  const useJwkAuth =
    clientConfig.requireClientSecret && options.clientAuthentication === "jwk";

  const usings = ["using Duende.AccessTokenManagement;"];

  if (clientConfig.requireDPoP) {
    usings.push("using Duende.AccessTokenManagement.DPoP;");
  }

  const clientOptions = [
    '        client.TokenEndpoint = new Uri($"{authority}/connect/token");',
    "",
    `        client.ClientId = ClientId.Parse(${configuration(clientIdKey(CLIENT_CREDENTIALS_SECTION))}!);`,
  ];

  if (useJwkAuth) {
    clientOptions.push(
      "",
      "        // No ClientSecret - ClientAssertionService signs a private_key_jwt",
    );
  } else if (clientConfig.requireClientSecret) {
    const secret = options.useUserSecrets
      ? `${secretExpression(secretKey(CLIENT_CREDENTIALS_SECTION), true)}!`
      : csharpString(SECRET_PLACEHOLDER);

    clientOptions.push(`        client.ClientSecret = ClientSecret.Parse(${secret});`);
  }

  if (scopes.length > 0) {
    clientOptions.push(
      "",
      `        client.Scope = Scope.Parse(${csharpString(scopes.join(" "))});`,
    );
  }

  if (clientConfig.requireDPoP) {
    clientOptions.push(
      "",
      "        // The client requires DPoP - the token is bound to this key",
      `        client.DPoPJsonWebKey = DPoPProofKey.Parse(builder.Configuration[${csharpString(dPoPKey(CLIENT_CREDENTIALS_SECTION))}]!);`,
    );
  }

  return [
    ...usings,
    "",
    "var builder = Host.CreateApplicationBuilder(args);",
    "",
    `var authority = ${configuration(authorityKey(CLIENT_CREDENTIALS_SECTION))}!;`,
    "",
    "// Access tokens are cached here, so they are requested once per lifetime",
    "builder.Services.AddDistributedMemoryCache();",
    "",
    "builder.Services.AddClientCredentialsTokenManagement()",
    `    .AddClient(${csharpString(options.appName)}, client =>`,
    "    {",
    ...clientOptions,
    "    });",
    ...(useJwkAuth
      ? [
          "",
          "builder.Services.AddTransient<IClientAssertionService, ClientAssertionService>();",
        ]
      : []),
    "",
    "// Every request sent through this HttpClient carries a managed access token",
    `builder.Services.AddClientCredentialsHttpClient(${csharpString(options.appName)},`,
    `    ClientCredentialsClientName.Parse(${csharpString(options.appName)}),`,
    "    client =>",
    "    {",
    `        client.BaseAddress = new Uri(${csharpString(ensureTrailingSlash(options.apiBaseUrl))});`,
    "    });",
    "",
    "builder.Services.AddHostedService<ApiWorker>();",
    "",
    "builder.Build().Run();",
  ].join("\n");
};

